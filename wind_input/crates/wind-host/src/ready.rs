//! 就绪契约。

/// 输入会话的就绪状态。
///
/// # 为什么需要显式表达
///
/// 词库的反查/合并索引是**惰性构建**的：构造期只做到 mmap 打开，真正的聚合
/// （实测 88526 条）拖到第一次查询。桌面上这发生在常驻服务进程的 IPC 线程上，用户
/// 感知不到；Android 上它落在 **UI 线程**，真机实测首键同步阻塞 2.8 秒。
///
/// 契约里没有「未就绪」这个状态时，宿主只有两条路：忍受首键卡顿，或者自己猜
/// 「喂哪几个键能触发惰性构建」然后后台预跑一遍。后者是实际发生过的——而且**猜错了**：
/// 第一版漏掉了释放首显闸门的那一步，「预热」只花 3ms 就返回，等于没热。
///
/// 宿主不该去猜核心内部的惰性边界。
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Readiness {
    /// 尚未开始准备
    Idle,
    /// 后台准备中。宿主可照常收键（会阻塞到完成），也可先给用户一个提示。
    Preparing,
    /// 已就绪，按键路径不会再有一次性的大开销
    Ready,
    /// 准备失败（词库缺失/损坏）。仍可输入，但功能降级。
    Failed,
}

impl Readiness {
    pub fn is_ready(self) -> bool {
        matches!(self, Self::Ready)
    }
}
